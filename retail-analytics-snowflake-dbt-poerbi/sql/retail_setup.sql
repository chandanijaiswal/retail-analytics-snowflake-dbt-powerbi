CREATE SCHEMA IF NOT EXISTS DBT_DEMO_DB.RETAIL;

CREATE STAGE IF NOT EXISTS DBT_DEMO_DB.RAW.CSV_STAGE
  DIRECTORY = (ENABLE = TRUE);

CREATE OR REPLACE FILE FORMAT DBT_DEMO_DB.RAW.CSV_FORMAT
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  TRIM_SPACE = FALSE
  ENCODING = 'UTF8';

  SHOW STAGES IN SCHEMA DBT_DEMO_DB.RAW;
SHOW FILE FORMATS IN SCHEMA DBT_DEMO_DB.RAW;

CREATE OR REPLACE TABLE DBT_DEMO_DB.RAW.RAW_SALES (
  ORDER_ID VARCHAR, ORDER_DATE VARCHAR, CUSTOMER_ID VARCHAR,
  PRODUCT_CODE VARCHAR, STORE_CODE VARCHAR, QUANTITY VARCHAR,
  UNIT_PRICE VARCHAR, DISCOUNT VARCHAR, PAYMENT_MODE VARCHAR,
  ORDER_STATUS VARCHAR
);

CREATE OR REPLACE TABLE DBT_DEMO_DB.RAW.RAW_CUSTOMERS (
  CUSTOMER_ID VARCHAR, CUSTOMER_NAME VARCHAR, GENDER VARCHAR,
  CITY VARCHAR, STATE VARCHAR, PHONE VARCHAR, EMAIL VARCHAR,
  SIGNUP_DATE VARCHAR, SEGMENT VARCHAR
);

CREATE OR REPLACE TABLE DBT_DEMO_DB.RAW.RAW_PRODUCTS (
  PRODUCT_CODE VARCHAR, PRODUCT_NAME VARCHAR, CATEGORY VARCHAR,
  BRAND VARCHAR, COST_PRICE VARCHAR, LIST_PRICE VARCHAR
);

CREATE OR REPLACE TABLE DBT_DEMO_DB.RAW.RAW_STORES (
  STORE_CODE VARCHAR, STORE_NAME VARCHAR, CITY VARCHAR, STATE VARCHAR,
  REGION VARCHAR, STORE_TYPE VARCHAR, OPEN_DATE VARCHAR
);

CREATE STAGE IF NOT EXISTS DBT_DEMO_DB.RAW.CSV_STAGE
  DIRECTORY = (ENABLE = TRUE);

  LIST @DBT_DEMO_DB.RAW.CSV_STAGE;

  COPY INTO DBT_DEMO_DB.RAW.RAW_SALES
  FROM @DBT_DEMO_DB.RAW.CSV_STAGE
  FILES = ('raw_sales.csv')
  FILE_FORMAT = (FORMAT_NAME = 'DBT_DEMO_DB.RAW.CSV_FORMAT');

  SELECT * FROM DBT_DEMO_DB.RAW.RAW_SALES LIMIT 20;

COPY INTO DBT_DEMO_DB.RAW.RAW_CUSTOMERS
  FROM @DBT_DEMO_DB.RAW.CSV_STAGE
  FILES = ('raw_customers.csv')
  FILE_FORMAT = (FORMAT_NAME = 'DBT_DEMO_DB.RAW.CSV_FORMAT');

COPY INTO DBT_DEMO_DB.RAW.RAW_PRODUCTS
  FROM @DBT_DEMO_DB.RAW.CSV_STAGE
  FILES = ('raw_products.csv')
  FILE_FORMAT = (FORMAT_NAME = 'DBT_DEMO_DB.RAW.CSV_FORMAT');

  COPY INTO DBT_DEMO_DB.RAW.RAW_STORES
  FROM @DBT_DEMO_DB.RAW.CSV_STAGE
