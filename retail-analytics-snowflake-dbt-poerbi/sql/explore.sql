WITH m AS (
  SELECT MONTH(order_date) AS month_num,
         SUM(net_amount)   AS revenue
  FROM DBT_DEMO_DB.RETAIL.FCT_SALES
  WHERE order_status = 'Delivered'
  GROUP BY 1
)
SELECT month_num,
       ROUND(revenue, 0) AS revenue,
       ROUND((revenue - LAG(revenue) OVER (ORDER BY month_num))
             / LAG(revenue) OVER (ORDER BY month_num) * 100, 1) AS mom_pct
FROM m
ORDER BY month_num;